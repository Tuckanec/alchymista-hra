-- =========================================================
-- 1. TABULKA: UŽIVATELÉ (uzivatele)
-- =========================================================
CREATE TABLE IF NOT EXISTS public.uzivatele (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prezdivka TEXT NOT NULL UNIQUE,
    email TEXT UNIQUE,
    heslo TEXT DEFAULT NULL,                -- Pro dočasné hosty může být heslo NULL
    role TEXT DEFAULT 'hrac',               -- 'hrac' | 'guest' | 'admin'
    avatar_url TEXT,                        -- Odkaz na profilový obrázek ve Storage
    games_played INT DEFAULT 0,             -- Celkový počet odehraných her
    games_won INT DEFAULT 0,                -- Počet vyhraných her
    skulls_drawn INT DEFAULT 0,             -- Počet vytažených smrtících lebek
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- =========================================================
-- 2. TABULKA: MÍSTNOSTI / PÁRTY (rooms)
-- =========================================================
CREATE TABLE IF NOT EXISTS public.rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code TEXT NOT NULL UNIQUE,
    room_name TEXT,                         -- Zobrazovaný název párty / laboratoře
    host_id BIGINT NOT NULL REFERENCES public.uzivatele(id) ON DELETE CASCADE,
    is_public BOOLEAN DEFAULT TRUE,         -- Zda je párty viditelná v seznamu aktivních místností
    status TEXT DEFAULT 'waiting',          -- 'waiting' | 'playing' | 'finished'
    game_status TEXT DEFAULT 'waiting',     -- 'waiting' | 'playing' | 'finished'
    current_turn_player_id BIGINT REFERENCES public.uzivatele(id) ON DELETE SET NULL,
    deck JSONB DEFAULT '[]'::jsonb,         -- Dobírací balíček karet ('safe' / 'killer')
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- =========================================================
-- 3. TABULKA: HRÁČI V MÍSTNOSTI (room_players)
-- =========================================================
CREATE TABLE IF NOT EXISTS public.room_players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code TEXT NOT NULL REFERENCES public.rooms(room_code) ON DELETE CASCADE,
    player_id BIGINT NOT NULL REFERENCES public.uzivatele(id) ON DELETE CASCADE,
    is_guest BOOLEAN DEFAULT FALSE,
    is_host BOOLEAN DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'pending', -- 'pending' (čeká na schválení) | 'approved'
    is_dead BOOLEAN DEFAULT FALSE,          -- Vyřazen ze hry vytažením lebky
    hand JSONB DEFAULT '[]'::jsonb,         -- Karty v ruce hráče
    joined_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_player_in_room UNIQUE (room_code, player_id)
);

-- =========================================================
-- 4. TABULKA: PŘÁTELSTVÍ (friendships)
-- =========================================================
CREATE TABLE IF NOT EXISTS public.friendships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES public.uzivatele(id) ON DELETE CASCADE,
    addressee_id BIGINT NOT NULL REFERENCES public.uzivatele(id) ON DELETE CASCADE,
    status TEXT DEFAULT 'pending',          -- 'pending' | 'accepted'
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_friendship UNIQUE (requester_id, addressee_id)
);

-- =========================================================
-- INDEXY PRO RYCHLÉ VYHLEDÁVÁNÍ A REALTIME
-- =========================================================
CREATE INDEX IF NOT EXISTS idx_rooms_is_public ON public.rooms(is_public);
CREATE INDEX IF NOT EXISTS idx_room_players_room_code ON public.room_players(room_code);
CREATE INDEX IF NOT EXISTS idx_room_players_player_id ON public.room_players(player_id);
CREATE INDEX IF NOT EXISTS idx_friendships_requester ON public.friendships(requester_id);
CREATE INDEX IF NOT EXISTS idx_friendships_addressee ON public.friendships(addressee_id);

-- =========================================================
-- REPLICA IDENTITY (pro spolehlivé Realtime DELETE payloady)
-- =========================================================
ALTER TABLE public.rooms REPLICA IDENTITY FULL;
ALTER TABLE public.room_players REPLICA IDENTITY FULL;
ALTER TABLE public.friendships REPLICA IDENTITY FULL;

-- =========================================================
-- ROW LEVEL SECURITY (RLS) & BEZPEČNOSTNÍ POLITIKY
-- =========================================================
ALTER TABLE public.uzivatele ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.room_players ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.friendships ENABLE ROW LEVEL SECURITY;

-- Politiky pro uzivatele
DROP POLICY IF EXISTS "Public select uzivatele" ON public.uzivatele;
CREATE POLICY "Public select uzivatele" ON public.uzivatele FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public insert uzivatele" ON public.uzivatele;
CREATE POLICY "Public insert uzivatele" ON public.uzivatele FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Public update uzivatele" ON public.uzivatele;
CREATE POLICY "Public update uzivatele" ON public.uzivatele FOR UPDATE USING (true);

-- Politiky pro rooms
DROP POLICY IF EXISTS "Public rooms policy" ON public.rooms;
CREATE POLICY "Public rooms policy" ON public.rooms FOR ALL USING (true) WITH CHECK (true);

-- Politiky pro room_players
DROP POLICY IF EXISTS "Public room_players policy" ON public.room_players;
CREATE POLICY "Public room_players policy" ON public.room_players FOR ALL USING (true) WITH CHECK (true);

-- Politiky pro friendships
DROP POLICY IF EXISTS "Public friendships policy" ON public.friendships;
CREATE POLICY "Public friendships policy" ON public.friendships FOR ALL USING (true) WITH CHECK (true);

-- =========================================================
-- SUPABASE REALTIME REPLIKACE
-- =========================================================
DO $$
BEGIN
    BEGIN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.rooms;
    EXCEPTION WHEN duplicate_object THEN
        NULL;
    END;

    BEGIN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.room_players;
    EXCEPTION WHEN duplicate_object THEN
        NULL;
    END;

    BEGIN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.friendships;
    EXCEPTION WHEN duplicate_object THEN
        NULL;
    END;
END
$$;

-- =========================================================
-- STORAGE BUCKET: AVATARS & POLITIKY PRO NAHRÁVÁNÍ OBRÁZKŮ
-- =========================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('avatars', 'avatars', true)
ON CONFLICT (id) DO UPDATE SET public = true;

DROP POLICY IF EXISTS "Public Read Avatars" ON storage.objects;
CREATE POLICY "Public Read Avatars" ON storage.objects FOR SELECT USING (bucket_id = 'avatars');

DROP POLICY IF EXISTS "Public Insert Avatars" ON storage.objects;
CREATE POLICY "Public Insert Avatars" ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'avatars');

DROP POLICY IF EXISTS "Public Update Avatars" ON storage.objects;
CREATE POLICY "Public Update Avatars" ON storage.objects FOR UPDATE USING (bucket_id = 'avatars');

DROP POLICY IF EXISTS "Public Delete Avatars" ON storage.objects;
CREATE POLICY "Public Delete Avatars" ON storage.objects FOR DELETE USING (bucket_id = 'avatars');
